export async function renderPaperPdf(paper: {
  id: string;
  title: string;
  totalMarks: number;
  sections: { title: string; instruction?: string | null; questions: any[] }[];
}): Promise<string> {
  const html = buildPaperHtml(paper);
  const katexCss = await selfContainedKatexCss();

  const browser = await chromium.launch();
  try {
    const page = await browser.newPage();
    await page.setContent(html, { waitUntil: "domcontentloaded" });
    await page.addStyleTag({ content: katexCss });
    await page.waitForTimeout(250); // let fonts settle
    const pdf = await page.pdf({ format: "A4", printBackground: true });

    // Upload to R2 (or local fallback)
    const key = await uploadPaper(paper.id, pdf);
    return key; // Return the object key (which serves as the storage identifier)
  } finally {
    await browser.close();
  }
}
